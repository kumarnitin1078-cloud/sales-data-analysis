#Is the refurbished discount high enough to cannibalize new product sales--

SELECT `condition`, round(avg(Discount_Pct),2) as discount
from apple
where discount_pct>0
group by `condition`;

# price trends over time from launch (Launch_Price_USD/INR) to current listing price (Current_Price_USD/INR)

select 
 row_number () over(partition by (product_category)order by launched_year) as no_of_product,
product_category,
launched_year,
 round( 100*((Launch_Price_USD -Current_Price_USD) /Launch_Price_USD),1) as  price_drop_by_percentage_USD,
round( 100*((Launch_Price_INR-Current_Price_INR) /Launch_Price_INR),1) as price_drop_by_percentage_INR
from
(select year(date) as launched_year, product_category,
avg(Launch_Price_USD) as Launch_Price_USD,
avg(Current_Price_USD) as Current_Price_USD,
avg(Launch_Price_INR) as Launch_Price_INR,
avg(Current_Price_INR) as Current_Price_INR
from apple
group by year(date),Product_Category) as t
order by product_category;

