#total  revenue  per model

select  distinct Model_Name,
Launch_Price_USD*count(Model_Name)  as revenue_USD,
Launch_Price_INR*count(Model_Name)  as revenue_INR
from apple
group by Model_Name,Launch_Price_USD,Launch_Price_INR
order by Model_Name;

#total revenue per year

select 
distinct `year`,
sum(`count`)*sum(Launch_Price_USD) as revenue_USD,
sum(`count`)*sum(Launch_Price_INR)as revenue_INR 
from
 (select  year(date) as `year`,
 count(Product_Category) as `count`,
 Launch_Price_USD,
 Launch_Price_INR
 from apple
 group by Launch_Price_USD, Launch_Price_INR,
`year`) as t
group by `year`;

#revenue generated by events 

select distinct Sale_Event ,
count(Sale_Event)*sum(Launch_Price_USD) as revenue_USD,
count(Sale_Event)*sum(Launch_Price_INR) as revenue_INR 
from apple
group by Sale_Event;


#  year and month wise selling of products

select  rank() over(partition by Product_Category,year(date) order by  count(Product_Category) ) as `no.`,
Product_Category,
 year(date) as `year`,monthname(date) as `month`,
 count(Product_Category) as `count` 
from apple
group by Product_Category,`year`,`month`
order by `year`;

